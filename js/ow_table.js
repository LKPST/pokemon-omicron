// Helper utility to get frame indices based on direction and animation step
window.getOverworldFrame = function(direction, step = 0) {
  // direction: 'down', 'left', 'right', 'up'
  // step: 0 (standing), 1 (walk step 1), 2 (walk step 2)
  
  const rowMap = {
    'down': 0,  // Row 0
    'left': 1,  // Row 1
    'right': 2, // Row 2
    'up': 3     // Row 3
  };

  const row = rowMap[direction] !== undefined ? rowMap[direction] : 0;
  let col = 0;

  // Custom column mapping based on your exact sequence rules
  if (direction === 'up') {
    // Up uses walking right/left frames from columns 1 and 3
    if (step === 1) col = 1; // walking right frame
    else if (step === 2) col = 3; // walking left frame
    else col = 0; // standing
  } else if (direction === 'right') {
    // Right uses columns 1 and 2/3 for proper right/left stepping
    if (step === 1) col = 1;
    else if (step === 2) col = 2;
    else col = 0;
  } else {
    // Standard sequence for Down and Left
    if (step === 1) col = 1; // walking right 1
    else if (step === 2) col = 3; // walking left 1
    else col = 0; // standing
  }

  // 4 columns total per row
  return (row * 4) + col;
};

// Frame lookup that honours each sprite's frameMap (set in the Overworld Sprite Editor).
// anim: 'walk' | 'run' | 'cycle' | 'surf' | 'fish' | 'fly'   step: 0 = stand, 1.. = animation steps.
// Falls back to getOverworldFrame (the fixed 4x4 layout) when a sprite has no frameMap for that animation.
window.getOverworldFrameFor = function(name, anim, direction, step = 0) {
  const e = window.OverworldTable && window.OverworldTable[name];
  const m = e && e.frameMap && e.frameMap[anim] && e.frameMap[anim][direction];
  if (m && m.length) return m[Math.min(step, m.length - 1)];
  return window.getOverworldFrame(direction, step);
};
